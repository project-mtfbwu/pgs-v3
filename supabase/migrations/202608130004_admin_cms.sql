create or replace function private.audit_admin_change()
returns trigger language plpgsql security definer set search_path = '' as $$
declare before_row jsonb; after_row jsonb; payload jsonb; entity text;
begin
  before_row := case when tg_op in ('UPDATE','DELETE') then to_jsonb(old) else '{}'::jsonb end;
  after_row := case when tg_op in ('INSERT','UPDATE') then to_jsonb(new) else '{}'::jsonb end;
  payload := case when tg_op = 'DELETE' then before_row else after_row end;
  entity := coalesce(payload->>'id', payload->>'slug', payload->>'key', payload->>'user_id', payload->>'student_id');
  insert into public.admin_audit_logs(actor_id,action,domain,entity_type,entity_id,old_values,new_values)
  values(auth.uid(),lower(tg_op),case
    when tg_table_name in ('cms_pages','cms_page_revisions','media_assets') then 'cms'
    when tg_table_name in ('enquiries','lead_submissions','study_journey_enquiries','deadline_subscriptions') then 'leads'
    when tg_table_name in ('staff_profiles','staff_role_assignments') then 'staff'
    when tg_table_name in ('site_settings') then 'settings'
    when tg_table_name in ('faqs','weekly_wall_items','key_dates','urgent_deadlines','study_abroad_facts','pgs_stats','testimonials','content_people','site_notices','legal_documents','site_social_links','university_meeting_slots','premium_content_settings') then 'content'
    else 'catalog' end,
    tg_table_name,entity,before_row,after_row);
  if tg_op = 'DELETE' then return old; end if; return new;
end;
$$;

