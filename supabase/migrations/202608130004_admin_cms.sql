create or replace function private.has_staff_permission(permission_key text)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.staff_profiles sp
    join public.staff_role_assignments a on a.staff_user_id = sp.user_id and a.revoked_at is null
    join public.staff_role_permissions rp on rp.role_id = a.role_id
    join public.staff_permissions p on p.id = rp.permission_id
    where sp.user_id = auth.uid() and sp.status = 'active' and p.key = permission_key
  )
$$;
revoke all on function private.has_staff_permission(text) from public;
grant execute on function private.has_staff_permission(text) to authenticated;

create or replace function private.current_staff_role()
returns text language sql stable security definer set search_path = '' as $$
  select r.key from public.staff_profiles sp
  join public.staff_role_assignments a on a.staff_user_id = sp.user_id and a.revoked_at is null
  join public.staff_roles r on r.id = a.role_id
  where sp.user_id = auth.uid() and sp.status = 'active'
  order by case r.key when 'super_admin' then 1 when 'admin' then 2 when 'mentor' then 3 else 4 end limit 1
$$;

