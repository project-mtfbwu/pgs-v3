create or replace function private.queue_public_submission()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into private.integration_outbox (event_type, entity_table, entity_id, deduplication_key, status)
  values ('public_submission.created', tg_table_name, new.id::text, tg_table_name || ':' || new.id::text, 'disabled');
  return new;
end;
$$;

