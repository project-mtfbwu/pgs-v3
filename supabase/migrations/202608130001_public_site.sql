create or replace function public.publish_cms_revision(target_page uuid, target_revision uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not exists (select 1 from public.cms_editors where user_id = auth.uid()) then
    raise exception 'not authorized';
  end if;
  if not exists (select 1 from public.cms_page_revisions where id = target_revision and page_id = target_page) then
    raise exception 'revision does not belong to page';
  end if;
  update public.cms_pages
  set published_revision_id = target_revision, status = 'published', updated_at = now()
  where id = target_page;
end;
$$;

